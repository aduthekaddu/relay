/** Glyph width and height in font pixels. */
export const DOT_W = 5
export const DOT_H = 7

/** Rows of booleans for a character (unknown characters render blank). */
export function glyph(ch: string): boolean[][] {
  const g = G[ch.toUpperCase()] ?? G[' ']!
  return g.split('|').map((row) => [...row].map((c) => c === '#'))
}

/** Width in font pixels of a string with `gap` columns between glyphs. */
export function measure(text: string, gap = 1): number {
  const n = [...text].length
  return n === 0 ? 0 : n * DOT_W + (n - 1) * gap
}

/** Visit every lit pixel of `text` laid out from (0,0). */
export function eachDot(text: string, visit: (x: number, y: number) => void, gap = 1): void {
  let ox = 0
  for (const ch of text) {
    const rows = glyph(ch)
    for (let y = 0; y < DOT_H; y++) {
      const row = rows[y]!
      for (let x = 0; x < DOT_W; x++) if (row[x]) visit(ox + x, y)
    }
    ox += DOT_W + gap
  }
}

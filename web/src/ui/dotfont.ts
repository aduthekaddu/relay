/** Characters the dot font can draw (besides lowercase letters). */
export const DOT_CHARS: string = Object.keys(F).join('')

const EMPTY = F[' ']

/** The seven 5-character rows for `ch` (lowercase maps to uppercase). */
export function dotRows(ch: string): string[] {
  return (F[ch.toUpperCase()] ?? EMPTY).split(' ')
}

/** Lit dot coordinates [col,row] for a string, with a 1-column gap between cells. */
export function dotLayout(text: string): {
  cols: number
  on: Array<[number, number]>
  off: Array<[number, number]>
} {
  const on: Array<[number, number]> = []
  const off: Array<[number, number]> = []
  const chars = [...text]
  chars.forEach((ch, i) => {
    const rows = dotRows(ch)
    const x0 = i * 6
    for (let y = 0; y < 7; y++) for (let x = 0; x < 5; x++) (rows[y][x] === '#' ? on : off).push([x0 + x, y])
  })
  return { cols: Math.max(0, chars.length * 6 - 1), on, off }
}
